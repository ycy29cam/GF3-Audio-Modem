FILE_BIN = np.load(FILE_BIN_DIR) #   To be generated by the file encoder


CHIRP_ATTEN = 0.80  # scale applied to both chirps
TARGET_PEAK = 0.80  # peak of every OFDM block after scaling
#LENGTH_TOL = 10
